#!/bin/sksh
# 2-pipes.sh — 管道和重定向
#
# 每个程序生来就有三个打开的“文件”：0 标准输入、1 标准输出、2 标准错误。
# 管道和重定向，就是 shell 在启动程序之前，悄悄把这三个文件换成别的东西。

# 管道 |：前一个命令的输出，直接接到后一个命令的输入（内核里是一块缓冲区）
echo "系统里的进程表一共有这么多行（第一行是表头）："
ps | wc -l

# > 把输出写进文件（覆盖），>> 追加到文件末尾
echo "第一行：今天学了管道" > /tmp/笔记.txt
echo "第二行：还学了重定向" >> /tmp/笔记.txt
date >> /tmp/笔记.txt

# < 让程序从文件读输入
echo "笔记的内容："
cat < /tmp/笔记.txt

# 2> 只把“错误信息”存到文件里，正常输出不受影响
cat /没有这个文件 2> /tmp/错误.txt
echo "刚才的错误信息被存进了 /tmp/错误.txt，内容是："
cat /tmp/错误.txt

# 管道可以一级一级接下去：列出所有内存文件系统 (tmpfs)，再排个序
echo "挂载在内存里的文件系统："
cat /proc/mounts | grep tmpfs | sort
